/**
 * Builds ignored .env.agent / .env.seller / .env.worker from root .env
 * without printing secret values. Does not overwrite existing files unless --force.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { randomBytes } from "node:crypto";

function parseEnv(raw) {
  const env = {};
  for (const line of raw.split(/\r?\n/)) {
    if (!line || line.trim().startsWith("#")) continue;
    const i = line.indexOf("=");
    if (i < 1) continue;
    env[line.slice(0, i).trim().replace(/^\uFEFF/, "")] = line.slice(i + 1).trim();
  }
  return env;
}

function writeIfNeeded(path, body, force) {
  if (existsSync(path) && !force) {
    console.log(`keep ${path}`);
    return;
  }
  writeFileSync(path, body, { encoding: "utf8", mode: 0o600 });
  console.log(`wrote ${path}`);
}

